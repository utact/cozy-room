export function pickTopics(count: number, rng: () => number = Math.random): Topic[] {
  const pool = [...TOPICS];
  const picked: Topic[] = [];
  while (picked.length < count && pool.length > 0) {
    const i = Math.floor(rng() * pool.length);
    picked.push(pool.splice(i, 1)[0]);
  }
  return picked;
}
